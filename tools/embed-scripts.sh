#!/bin/sh
# embed-scripts.sh FILE... > vtesse_scripts.h
#
# Turns the scripts from scripts/ into NUL-terminated byte arrays, so that the
# binary carries them (built-in hook, "vtesse --install"). Byte arrays instead of
# string literals: no escaping, and no limit on the length of a literal.
set -e

echo "/* generated by tools/embed-scripts.sh from scripts/: do not edit */"
for f in "$@"; do
    name=$(basename "$f" | tr -c 'A-Za-z0-9\n' '_')
    echo "static const unsigned char script_${name}[] = {"
    od -An -v -tu1 "$f" | awk '{ line = "   "; for (i = 1; i <= NF; i++) line = line " " $i ","; print line }'
    echo "    0"
    echo "};"
done
echo "static const struct { const char *name; const char *text; } embedded_scripts[] = {"
for f in "$@"; do
    name=$(basename "$f" | tr -c 'A-Za-z0-9\n' '_')
    echo "    { \"$(basename "$f")\", (const char *)script_$name },"
done
echo "};"
